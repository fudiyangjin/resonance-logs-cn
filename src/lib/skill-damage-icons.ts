import presets from "./config/skill-icon-presets.json";
import talentGroupsRaw from "./config/talent-icon-groups.json";
import talentNamesZhCN from "./config/talent_icon_names.json";
import type { AppLocale } from "./i18n/locales";
import { getClassConfigs } from "./skill-mappings";
import type { SkillDamageGroup } from "./skill-damage-settings";

/** One talent tree section of a class; `stageId` null is the class-wide part. */
export type TalentIconSection = {
  stageId: number | null;
  icons: readonly string[];
};

type TalentIconGroups = {
  classes: { classKey: string; sections: TalentIconSection[] }[];
  common: string[];
};

type TalentIconNames = Record<string, string[] | undefined>;

/** Generated by `scripts/extract_talent_icons.py`. */
const TALENT_GROUPS = talentGroupsRaw as TalentIconGroups;
const TALENT_NAMES_ZH_CN = talentNamesZhCN as TalentIconNames;
const LOCALIZED_TALENT_NAMES = import.meta.glob(
  "./config/*/talent_icon_names.json",
  { eager: true, import: "default" },
) as Record<string, TalentIconNames | undefined>;

/** Picker tab holding the attribute placeholder icons shared by every class. */
export const TALENT_COMMON_TAB = "common";

export const SKILL_DAMAGE_ICON_PRESETS: readonly string[] = presets;
export const TALENT_COMMON_ICONS: readonly string[] = TALENT_GROUPS.common;
export const TALENT_DAMAGE_ICON_PRESETS: readonly string[] = [
  ...new Set([
    ...TALENT_GROUPS.common,
    ...TALENT_GROUPS.classes.flatMap((group) =>
      group.sections.flatMap((section) => section.icons),
    ),
  ]),
].sort();
const skillPresetPaths = new Set(SKILL_DAMAGE_ICON_PRESETS);
const presetPaths = new Set([
  ...SKILL_DAMAGE_ICON_PRESETS,
  ...TALENT_DAMAGE_ICON_PRESETS,
]);

const SKILL_ICON_PATH = /^\/images\/([^/]+)\/skill\/[^/]+$/;

/** Class key of a class skill icon (`/images/<classKey>/skill/...`). */
export function skillIconClassKey(path: string): string | null {
  return SKILL_ICON_PATH.exec(path)?.[1] ?? null;
}

export const SKILL_ICONS_BY_CLASS: ReadonlyMap<string, readonly string[]> =
  (() => {
    const byClass = new Map<string, string[]>();
    for (const path of SKILL_DAMAGE_ICON_PRESETS) {
      const classKey = skillIconClassKey(path);
      if (!classKey) continue;
      const icons = byClass.get(classKey) ?? [];
      icons.push(path);
      byClass.set(classKey, icons);
    }
    return byClass;
  })();

const TALENT_SECTIONS_BY_CLASS = new Map(
  TALENT_GROUPS.classes.map((group) => [group.classKey, group.sections]),
);

const TALENT_ICON_OWNERS: ReadonlyMap<string, readonly string[]> = (() => {
  const owners = new Map<string, string[]>();
  const add = (path: string, owner: string) => {
    const list = owners.get(path) ?? [];
    if (!list.includes(owner)) list.push(owner);
    owners.set(path, list);
  };
  for (const group of TALENT_GROUPS.classes)
    for (const section of group.sections)
      for (const path of section.icons) add(path, group.classKey);
  for (const path of TALENT_GROUPS.common) add(path, TALENT_COMMON_TAB);
  return owners;
})();

const CLASS_BY_SPEC_STAGE = new Map(
  TALENT_GROUPS.classes.flatMap((group) =>
    group.sections.flatMap((section) =>
      section.stageId === null ? [] : [[section.stageId, group.classKey]],
    ),
  ),
);

export function talentIconSections(
  classKey: string,
): readonly TalentIconSection[] {
  return TALENT_SECTIONS_BY_CLASS.get(classKey) ?? [];
}

/** Picker tabs an icon appears under; empty for unknown paths. */
export function iconOwnerClasses(path: string): readonly string[] {
  if (skillPresetPaths.has(path)) {
    const classKey = skillIconClassKey(path);
    return classKey ? [classKey] : [];
  }
  return TALENT_ICON_OWNERS.get(path) ?? [];
}

/**
 * Tab the picker opens on: the selected icon's class (the loadout's class
 * when the icon is shared), else the class of the loadout's linked spec,
 * else the first class.
 */
export function initialIconPickerClass(input: {
  path: string;
  linkedStageId: number | null | undefined;
  classKeys: readonly string[];
}): string {
  const { path, linkedStageId, classKeys } = input;
  const linkedClass =
    linkedStageId == null ? undefined : CLASS_BY_SPEC_STAGE.get(linkedStageId);
  const owners = iconOwnerClasses(path).filter(
    (owner) => owner === TALENT_COMMON_TAB || classKeys.includes(owner),
  );
  if (owners.length > 0)
    return linkedClass && owners.includes(linkedClass)
      ? linkedClass
      : owners[0]!;
  if (linkedClass && classKeys.includes(linkedClass)) return linkedClass;
  return classKeys[0] ?? "";
}

function fileName(path: string): string {
  return path.slice(path.lastIndexOf("/") + 1);
}

/** Official talent names using this icon; falls back to Chinese. */
export function talentIconNames(
  path: string,
  locale: AppLocale,
): readonly string[] {
  const file = fileName(path);
  const localized =
    LOCALIZED_TALENT_NAMES[`./config/${locale}/talent_icon_names.json`]?.[file];
  return localized?.length ? localized : (TALENT_NAMES_ZH_CN[file] ?? []);
}

const skillIconNames = new Map<AppLocale, ReadonlyMap<string, string>>();

function skillIconNameMap(locale: AppLocale): ReadonlyMap<string, string> {
  const cached = skillIconNames.get(locale);
  if (cached) return cached;
  const names = new Map<string, string>();
  for (const config of getClassConfigs(locale)) {
    for (const skill of config.skills)
      if (!names.has(skill.imagePath)) names.set(skill.imagePath, skill.name);
    for (const derivation of config.derivations ?? [])
      if (!names.has(derivation.derivedImagePath))
        names.set(derivation.derivedImagePath, derivation.derivedName);
  }
  skillIconNames.set(locale, names);
  return names;
}

/** Hover text for a preset icon; empty when no name is known. */
export function presetIconTitle(path: string, locale: AppLocale): string {
  if (skillPresetPaths.has(path))
    return skillIconNameMap(locale).get(path) ?? "";
  return talentIconNames(path, locale).join(" / ");
}

/** Icon plate background with the group's opacity applied to every stop. */
export function skillDamageIconBackground(
  group: Pick<SkillDamageGroup, "iconBackground" | "iconBackgroundOpacity">,
): string {
  const paint = group.iconBackground;
  const rgba = (color: string) =>
    `rgba(${parseInt(color.slice(1, 3), 16)}, ${parseInt(color.slice(3, 5), 16)}, ${parseInt(color.slice(5, 7), 16)}, ${group.iconBackgroundOpacity})`;
  return paint.mode === "gradient"
    ? `linear-gradient(${paint.angle}deg, ${rgba(paint.color)}, ${rgba(paint.endColor)})`
    : rgba(paint.color);
}

export function resolveSkillDamageIcon(path: string): string | null {
  return presetPaths.has(path) ? path : null;
}
